#!/usr/bin/env python3
"""Build deliverables/01-evidence-ledger.md, 01b-uncertainty-register.md and
evidence/DIGEST.md mechanically from evidence/E*.md. Usage: build_ledger.py (run from repo root)."""
import glob, os, re
files = sorted(glob.glob('evidence/E0*.md'))
ENTRY = re.compile(r'^#{2,4}\s+(E\d\d(?:-[A-Z])?-\d+[a-z]?)\s*[—–:-]+\s*(.*)$')
HEAD = re.compile(r'^(#{1,4})\s+(.*)$')
def sections(lines):
    out, cur, title, lvl = [], [], None, 0
    for l in lines:
        m = HEAD.match(l)
        if m and len(m.group(1)) <= 2:
            if title is not None: out.append((title, cur))
            title, cur = m.group(2).strip(), []
        elif title is not None: cur.append(l)
    if title is not None: out.append((title, cur))
    return out
rows, unc, digest, counts = [], [], [], {}
for f in files:
    lines = open(f, encoding='utf-8').read().split('\n')
    stream = os.path.basename(f)[:3]
    i = 0
    while i < len(lines):
        m = ENTRY.match(lines[i])
        if m:
            eid, claim = m.group(1), m.group(2).strip()
            label = src = ''
            j = i + 1
            while j < len(lines) and not HEAD.match(lines[j]):
                t = lines[j].strip().lstrip('-* ').strip()
                if t.lower().startswith('label:') and not label: label = t[6:].strip()
                if t.lower().startswith('source:') and not src: src = t[7:].strip()
                j += 1
            lab = 'VERIFIED' if 'VERIFIED' in label.upper() and 'INFERRED' not in label.upper() else ('INFERRED' if 'INFERRED' in label.upper() and 'VERIFIED' not in label.upper() else (label[:40] or '?'))
            counts[lab] = counts.get(lab, 0) + 1
            def cell(s, n):
                # Truncate at the last whitespace before the limit so a `sha:path[:line]`
                # citation is never cut mid-token (a cut token fails verify_citations.py).
                s = s.replace('|', '\\|')
                if len(s) <= n: return s
                cut = s.rfind(' ', 0, n + 1)
                return (s[:cut] if cut > 0 else s[:n]).rstrip() + '…'
            rows.append(f'| {eid} | {cell(claim, 160)} | {cell(label, 60)} | {cell(src, 220)} | [{os.path.basename(f)}](../{f}) |')
            i = j
        else: i += 1
    secs = sections(lines)
    dig = [f'\n# {os.path.basename(f)}\n']
    for title, body in secs:
        tl = title.lower()
        if tl.startswith('0') or 'summary' in tl or 'takeaway' in tl or 'open question' in tl or 'uncertaint' in tl:
            dig += [f'## {title}'] + body
        if 'open question' in tl or 'uncertaint' in tl:
            unc += [f'\n## {stream} — {title} ([{os.path.basename(f)}](../{f}))'] + body
    digest += dig
os.makedirs('deliverables', exist_ok=True)
open('evidence/DIGEST.md', 'w').write('# Evidence digest (generated by scripts/build_ledger.py — summaries, open questions and takeaways of every stream)\n' + '\n'.join(digest) + '\n')
open('deliverables/01-evidence-ledger.md', 'w').write(
 '# 01 — Source / evidence ledger\n\n_Generated by `scripts/build_ledger.py` from `evidence/E00`–`E09`. Do not edit by hand; edit the evidence file and regenerate._\n\n'
 '## Sources and their reliability\n\n| Class | Source | Access | Fidelity |\n|---|---|---|---|\n'
 '| Git (primary) | `storytold/photocraft` full clone, pinned `74330157cb601573ae4523a95bb9132822fc3918`, 12,396 commits on main, ~370 branches, 27 tags, 6,480 PR heads | local clone | exact; every citation machine-checkable with `scripts/verify_citations.py` |\n'
 '| Repo documents (primary) | AGENTS.md (38 revisions), docs/, README, workflows, scorecard, xtask | via git at cited sha | exact |\n'
 '| GitHub PR / issue pages (primary, degraded) | sampled PR and issue pages | WebFetch only (API blocked) | model-summarized, short quotes — treat as lower fidelity |\n'
 '| Developer statements (primary, self-reported) | project sites, org RFCs, founder HN comments (identity of HN account inferred) | web | verbatim where fetched; claims about method are self-reported |\n'
 '| Press / third parties | articles, reviews | web, several blocked (403) | only "source X claims Y" |\n'
 '| Not accessible | private `plan/`, `log/devlog.md` (gitignored), private rules repo history, Discord, GitHub API metadata (who squash-merged, review states), Reddit | — | unknown |\n\n'
 f'## Entry counts\n\n{len(rows)} evidence entries: ' + ', '.join(f'{k}: {v}' for k, v in sorted(counts.items(), key=lambda x: -x[1])) + '.\n\n'
 '## Ledger\n\n| ID | Claim | Label | Primary source | File |\n|---|---|---|---|---|\n' + '\n'.join(rows) + '\n')
open('deliverables/01b-uncertainty-register.md', 'w').write(
 '# 01b — Uncertainty register\n\n_Generated by `scripts/build_ledger.py`: the "Open questions / uncertainties" section of every evidence stream, verbatim._\n\n'
 '## Cross-cutting limits\n\n'
 '- A commit without an AI trailer is **attribution unknown**, not human. 4,199 of 8,329 non-merge commits carry no AI marker (E03).\n'
 '- House rule 15 ("No agent attribution", 2026-11-06) reduces trailer evidence after that date.\n'
 '- Git does not record who pressed "squash and merge", review states, or open/closed status; PR-page evidence comes from a small WebFetch sample.\n'
 '- The founder\'s planning (`plan/`), dev log (`log/devlog.md`) and prompts are private; orchestration tooling, agent counts at any moment, token/dollar cost and human supervision time are not published.\n'
 '- Agent-hours and concurrency figures in project docs are self-reported and derived, not metered.\n'
 + '\n'.join(unc) + '\n')
print(len(rows), counts, sum(len(x) for x in digest))
